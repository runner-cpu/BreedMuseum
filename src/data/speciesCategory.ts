/** 未登记物种回落到“其他”，由契约测试提示补充映射。 */
export const categoryForSpecies = (species: string): BreedCategory =>
  SPECIES_CATEGORY[species] ?? '其他';

/** 物种是否已在映射表登记。 */
export const isMappedSpecies = (species: string): boolean => species in SPECIES_CATEGORY;
