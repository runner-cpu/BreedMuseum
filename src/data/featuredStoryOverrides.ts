/** 应用精选故事重写（未登记的品种保持原故事）。 */
export function applyFeaturedStories(items: readonly Breed[]): Breed[] {
  const keys = Object.keys(featuredStoryOverrides);
  if (keys.length === 0) return [...items];
  return items.map((breed) => {
    const story = featuredStoryOverrides[breed.id];
    return story && story !== breed.story ? { ...breed, story } : breed;
  });
}
